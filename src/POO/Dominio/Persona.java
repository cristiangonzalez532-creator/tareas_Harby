package POO.Dominio;

public class Persona {
    public String nombre;
    public String identificacion;
    public String Correo;
    public int edad;

    public Persona(String nombre, String identificacion, String correo, int edad) {
        this.nombre = nombre;
        this.identificacion = identificacion;
        Correo = correo;
        this.edad = edad;
    }
}
