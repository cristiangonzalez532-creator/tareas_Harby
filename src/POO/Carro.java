package POO;

public class Carro {

    public String marca;
    public int ano;
    public String tipo;
    public String placa;
    public String ciudad;
    public int motor;
    public String caja;
    public String combustible;
    public int puertas;
    public String nombre_dueño;


    public Carro(String marca, int ano, String tipo, String placa, String ciudad, int motor, String caja, String combustible, int puertas, String nombre_dueño) {
        this.marca = marca;
        this.ano = ano;
        this.tipo = tipo;
        this.placa = placa;
        this.ciudad = ciudad;
        this.motor = motor;
        this.caja = caja;
        this.combustible = combustible;
        this.puertas = puertas;
        this.nombre_dueño = nombre_dueño;
    }
}

