package POO;

public class Estrella {
    public String color;
    public int puntas;
    public String tamano;
    public int esquina;
    public int brillo;

    public Estrella(String color, int puntas, String tamano, int esquina, int brillo) {
        this.color = color;
        this.puntas = puntas;
        this.tamano = tamano;
        this.esquina = esquina;
        this.brillo = brillo;

    }
}
